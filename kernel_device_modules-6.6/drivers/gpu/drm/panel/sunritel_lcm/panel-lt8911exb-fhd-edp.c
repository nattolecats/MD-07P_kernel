static void check_is_need_fake_resolution(struct device *dev)
{
	unsigned int ret = 0;
	ret = of_property_read_u32(dev->of_node, "fake_heigh", &fake_heigh);
	if (ret) {
		need_fake_resolution = false;
		return;
	}
	ret = of_property_read_u32(dev->of_node, "fake_width", &fake_width);
	if (ret) {
		need_fake_resolution = false;
		return;
	}
	if (fake_heigh > 0 && fake_heigh < VAC && fake_width > 0 && fake_width < HAC)
		need_fake_resolution = true;
	else
		need_fake_resolution = false;
}
static int lcm_probe(struct mipi_dsi_device *dsi)
{
	struct device *dev = &dsi->dev;
	struct device_node *dsi_node, *remote_node = NULL, *endpoint = NULL;
	struct lcm *ctx;
	struct device_node *backlight;
	int ret;

	pr_info("%s+zlw\n", __func__);

	dsi_node = of_get_parent(dev->of_node);
	if (dsi_node) {
		endpoint = of_graph_get_next_endpoint(dsi_node, NULL);
		if (endpoint) {
			remote_node = of_graph_get_remote_port_parent(endpoint);
			if (!remote_node) {
				pr_info("No panel connected,skip probe lcm\n");
				return -ENODEV;
			}
			pr_info("zlw-lcm device node name:%s\n", remote_node->name);
		}
	}
	if (remote_node != dev->of_node) {
		pr_info("%s+ skip probe due to not current lcm\n", __func__);
		return -ENODEV;
	}

	ctx = devm_kzalloc(dev, sizeof(struct lcm), GFP_KERNEL);
	if (!ctx)
		return -ENOMEM;

	mipi_dsi_set_drvdata(dsi, ctx);

	ctx->dev = dev;
	dsi->lanes = 4;
	dsi->format = MIPI_DSI_FMT_RGB888;
	dsi->mode_flags = MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_VIDEO_SYNC_PULSE;

	backlight = of_parse_phandle(dev->of_node, "backlight", 0);
	if (backlight) {
		ctx->backlight = of_find_backlight_by_node(backlight);
		of_node_put(backlight);

		if (!ctx->backlight)
			return -EPROBE_DEFER;
	}
	pr_info("%s parse get power_gpio\n", __func__);
	ctx->power_gpio = devm_gpiod_get(ctx->dev, "power", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->power_gpio)) {
		dev_info(ctx->dev, "%s: cannot get power_gpio %ld\n",
			__func__, PTR_ERR(ctx->power_gpio));
		return PTR_ERR(ctx->power_gpio);
	}
	devm_gpiod_put(dev, ctx->power_gpio);
	// pr_info("%s parse get reset_gpio\n", __func__);
	// ctx->reset_gpio = devm_gpiod_get(dev, "reset", GPIOD_OUT_HIGH);
	// if (IS_ERR(ctx->reset_gpio)) {
		// dev_info(ctx->dev, "%s: cannot get reset-gpios %ld\n",
			// __func__, PTR_ERR(ctx->reset_gpio));
		// return PTR_ERR(ctx->reset_gpio);
	// }
	// devm_gpiod_put(dev, ctx->reset_gpio);

	ctx->blen_gpio = devm_gpiod_get(dev, "blen", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->blen_gpio)) {
		dev_info(dev, "%s: cannot get blen_gpio %ld\n",
			__func__, PTR_ERR(ctx->blen_gpio));
		return PTR_ERR(ctx->blen_gpio);
	}
	devm_gpiod_put(dev, ctx->blen_gpio);

	ctx->blpwr_gpio = devm_gpiod_get(dev, "blpwr", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->blpwr_gpio)) {
		dev_info(dev, "cannot get blpwr_gpio%ld\n",
			 PTR_ERR(ctx->blpwr_gpio));
		return PTR_ERR(ctx->blpwr_gpio);
	}
	ctx->edppwr_gpio = devm_gpiod_get(dev, "edppwr", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->edppwr_gpio)) {
		dev_info(dev, "%s: cannot get edppwr_gpio %ld\n",
			__func__, PTR_ERR(ctx->edppwr_gpio));
		return PTR_ERR(ctx->edppwr_gpio);
	}
	devm_gpiod_put(dev, ctx->edppwr_gpio);

	ctx->edprst_gpio = devm_gpiod_get(dev, "edprst", GPIOD_OUT_HIGH);
	if (IS_ERR(ctx->edprst_gpio)) {
		dev_info(dev, "cannot get edprst_gpio %ld\n",
			 PTR_ERR(ctx->edprst_gpio));
		return PTR_ERR(ctx->edprst_gpio);
	}

	ctx->prepared = true;
	ctx->enabled = true;

	drm_panel_init(&ctx->panel, dev, &lcm_drm_funcs, DRM_MODE_CONNECTOR_DSI);

	drm_panel_add(&ctx->panel);

	ret = mipi_dsi_attach(dsi);
	if (ret < 0)
		drm_panel_remove(&ctx->panel);

#if defined(CONFIG_MTK_PANEL_EXT)
	mtk_panel_tch_handle_reg(&ctx->panel);
	ret = mtk_panel_ext_create(dev, &ext_params, &ext_funcs, &ctx->panel);
	if (ret < 0)
		return ret;
#endif
	check_is_need_fake_resolution(dev);
	pr_info("%s-zlw\n", __func__);

	return ret;
}


static void lcm_remove(struct mipi_dsi_device *dsi)
{
	struct lcm *ctx = mipi_dsi_get_drvdata(dsi);
#if defined(CONFIG_MTK_PANEL_EXT)
	struct mtk_panel_ctx *ext_ctx = find_panel_ctx(&ctx->panel);
#endif

	mipi_dsi_detach(dsi);
	drm_panel_remove(&ctx->panel);

#if defined(CONFIG_MTK_PANEL_EXT)
	mtk_panel_detach(ext_ctx);
	mtk_panel_remove(ext_ctx);
#endif
}
